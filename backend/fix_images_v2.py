def run():
    conn = sqlite3.connect(DB)
    cursor = conn.cursor()
    rows = cursor.execute('SELECT id, name, subcategory FROM products').fetchall()
    updated = 0

    kit_idx = 0
    ball_idx = 0
    bolalar_idx = 0

    for pid, name, subcat in rows:
        url = NAME_TO_IMAGE.get(name)
        if not url:
            if subcat == 'Futbol kiyimlari':
                url = FOOTBALL_KIT_URLS[kit_idx % len(FOOTBALL_KIT_URLS)]
                kit_idx += 1
            elif subcat == 'Futbol toplari':
                url = FOOTBALL_BALL_URLS[ball_idx % len(FOOTBALL_BALL_URLS)]
                ball_idx += 1
            elif subcat == 'Bolalar kiyimi':
                url = BOLALAR_URLS[bolalar_idx % len(BOLALAR_URLS)]
                bolalar_idx += 1

        if url:
            cursor.execute('UPDATE products SET image_url=? WHERE id=?', (url, pid))
            updated += 1

    conn.commit()
    conn.close()
    print(f"✅ {updated} ta mahsulot rasmi yangilandi")


if __name__ == '__main__':
    run()
